const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const html=fs.readFileSync('index.html','utf8');
const context=vm.createContext({});
vm.runInContext(html.slice(html.indexOf('function topicOptionTree('),html.indexOf('function renderMultiSelect(')),context);
const options=['','A|||#block#one','A|||First','A|||Second','A|||Loose','B|||First'].map(value=>({value,selected:!value}));
const blocks=[{id:'one',subject:'A',name:'Block',topics:['First','Second','Deleted']}];
const tree=context.topicOptionTree(options,blocks);
const chosen=()=>options.filter(o=>o.value&&o.selected).map(o=>o.value);
const change=(value,checked)=>context.setTopicSelection(options,tree,value,checked);
assert.deepEqual(Array.from(tree[0].topics,o=>o.value),['A|||Loose']);
assert.deepEqual(Array.from(tree[0].blocks[0].topics,o=>o.value),['A|||First','A|||Second']);
assert.deepEqual(Array.from(tree[1].topics,o=>o.value),['B|||First']);
change('A|||#block#one',true);
assert.deepEqual(chosen(),['A|||#block#one']);
change('A|||First',false);
assert.deepEqual(chosen(),['A|||Second']);
change('A|||First',true);
assert.deepEqual(chosen(),['A|||#block#one']);
change('A|||Loose',true);
change('B|||First',true);
change('A|||#block#one',false);
assert.deepEqual(chosen(),['A|||Loose','B|||First']);
change('',true);
assert.deepEqual(chosen(),[]);
assert.equal(options[0].selected,true);
change('A|||First',true);
assert.equal(options[0].selected,false);
change('A|||First',false);
assert.equal(options[0].selected,true);
console.log('Passed: nested topics, ungrouped topics, subject isolation, whole-block and partial selection, and select-all fallback.');
